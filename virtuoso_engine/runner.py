"""
Persistent Virtuoso session runner.

Architecture
------------
Starts a single Virtuoso process with ``DISPLAY`` pointing to a pre-running
Xvfb instance (the user starts Xvfb in a separate tmux session).  SKILL
scripts are fed to Virtuoso via a **file-based job queue** so we avoid the
per-run process-startup overhead:

1. A unique job directory  ``/tmp/virt_job_<pid>/``  is created.
2. A SKILL "server loop" script is written there and passed via ``-replay``.
3. Virtuoso starts (no ``-nograph``; uses the Xvfb display) and enters the
   server loop, polling for work.
4. For each ``run_script()`` call:
   a. ``exit()`` calls are stripped from the script (so Virtuoso stays alive).
   b. The cleaned script path is written to ``pending.job``.
   c. Virtuoso loads the script; result written to ``result.done``.
   d. Python reads the result and returns a ``VirtuosoResult``.
5. On timeout or unexpected crash Virtuoso is restarted automatically
   (up to ``max_restarts`` times).

Prerequisites
-------------
An Xvfb display must already be running on the configured display number
**before** calling ``start()``, e.g. in a separate tmux session::

    Xvfb :99 -screen 0 1024x768x24 -extension XKEYBOARD &

The display number is configurable (default ``:99``).
"""

from __future__ import annotations

import os
import re
import subprocess
import tempfile
import time
from dataclasses import dataclass, field
from pathlib import Path
from typing import Optional


# ---------------------------------------------------------------------------
# Result container
# ---------------------------------------------------------------------------

@dataclass
class VirtuosoResult:
    success:       bool
    returncode:    int
    log_path:      Path
    log_text:      str   = ""
    stderr:        str   = ""
    elapsed_sec:   float = 0.0
    error_message: str   = ""


# ---------------------------------------------------------------------------
# SKILL server loop (embedded as a string; instantiated at runtime)
# ---------------------------------------------------------------------------

# {JOB_DIR} is replaced with the actual path before writing to disk.
#
# Job protocol (avoids fragile SKILL file-reading):
#   Python writes a SKILL expression to pending.job, e.g.:
#       load("/tmp/virt_clean_12345.il")
#   The server renames it to active.job and loads it directly.
#   Result is written to result.done ("DONE\n" or "ERROR <msg>\n").
_SERVER_SKILL_TEMPLATE = """\
; ============================================================
; Virtuoso SKILL Server — auto-generated by PersistentVirtuosoRunner
; Do NOT edit by hand.
;
; Job dir: {JOB_DIR}
;   pending.job  — Python writes a SKILL load() expression here
;   active.job   — server renames pending.job here while processing
;   result.done  — server writes DONE or ERROR <msg> here
;   shutdown     — Python creates this file to stop the server
; ============================================================

procedure( virtuosoSkillServer( jobDir )
    let( (jobFile activeJobFile resultFile err f _running)
        printf("[SkillServer] Starting. Job dir: %s\\n" jobDir)
        unless( isDir(jobDir) createDir(jobDir) )

        _running = t
        while( _running
            ; --- Shutdown check ---
            ; return() is not valid inside while; use a flag instead
            when( isFile( strcat(jobDir "/shutdown") )
                printf("[SkillServer] Shutdown signal received.\\n")
                _running = nil
            )

            when( _running
                ; --- Job check ---
                jobFile       = strcat(jobDir "/pending.job")
                activeJobFile = strcat(jobDir "/active.job")
                resultFile    = strcat(jobDir "/result.done")

                when( isFile(jobFile)
                    ; Atomically claim the job file
                    system(sprintf(nil "mv \\"%s\\" \\"%s\\"" jobFile activeJobFile))

                    ; The job file IS a SKILL expression, e.g.:
                    ;   load("/tmp/virt_clean_12345.il")
                    ;
                    ; errset evaluates its argument in an error-protected context.
                    ;   On success: returns list(result)  — truthy
                    ;   On error:   returns nil            — falsy; errset.errMsg has message
                    err = nil
                    let( (_result)
                        _result = errset( load(activeJobFile) t )
                        unless( _result
                            err = errset.errMsg
                            unless( err err = "Script failed (unknown SKILL error)" )
                        )
                    )

                    ; Write result marker
                    f = outfile(resultFile "w")
                    when( f
                        if( err then fprintf(f "ERROR %s\\n" err)
                        else         fprintf(f "DONE\\n") )
                        close(f)
                    )

                    ; Remove the active job file
                    system(sprintf(nil "rm -f \\"%s\\"" activeJobFile))
                )

                ; Brief sleep to avoid busy-waiting
                system("sleep 0.1")
            )
        )

        printf("[SkillServer] Exiting.\\n")
    )
)

virtuosoSkillServer("{JOB_DIR}")
"""


# ---------------------------------------------------------------------------
# Persistent runner
# ---------------------------------------------------------------------------

def _remove_virtuoso_lock_files(session_log: Path, label: str = "VirtuosoRunner") -> None:
    """
    Remove Cadence session lock files that prevent Virtuoso from starting.

    Virtuoso creates ``<session_log>`` and ``<session_log>.cdslck`` in the
    log directory.  If a previous run crashed, these files linger and block
    the next startup.  Call this before launching a new Virtuoso process.
    """
    log_dir = session_log.parent
    log_dir.mkdir(parents=True, exist_ok=True)
    for fname in [session_log.name, session_log.name + ".cdslck"]:
        f = log_dir / fname
        if f.exists():
            try:
                f.unlink()
                print(f"[{label}] Removed stale lock file: {f}")
            except OSError as exc:
                print(f"[{label}] Warning: could not remove {f}: {exc}")


class PersistentVirtuosoRunner:
    """
    Manages a single long-lived Virtuoso process that accepts SKILL jobs via
    a file-based queue.

    The user must start an Xvfb display **before** calling ``start()``::

        # In a separate tmux session:
        Xvfb :99 -screen 0 1024x768x24 -extension XKEYBOARD &

    Usage::

        runner = PersistentVirtuosoRunner(
            virtuoso_dir="/path/to/project",
            display=":99",
        )
        runner.start()
        result = runner.run_script(skill_file, log_file)
        runner.close()

        # Or as a context manager:
        with PersistentVirtuosoRunner(virtuoso_dir=...) as runner:
            result = runner.run_script(skill_file, log_file)
    """

    # Seconds to wait after launching Virtuoso before checking it's alive
    STARTUP_WAIT_SEC = 10
    # Seconds between job-completion polls
    POLL_INTERVAL = 0.5

    def __init__(
        self,
        virtuoso_dir: str | Path,
        display: str = ":99",
        session_log: Optional[Path] = None,
        default_timeout: int = 3600,
        max_restarts: int = 3,
        label: str = "VirtuosoRunner",
    ) -> None:
        self.virtuoso_dir    = Path(virtuoso_dir)
        self.display         = display
        self.default_timeout = default_timeout
        self.max_restarts    = max_restarts
        self._label          = label

        # Unique job directory per instance — pid alone is not enough when
        # multiple runners live in the same process (parallel workers).
        self._job_dir = Path(f"/tmp/virt_job_{os.getpid()}_{id(self)}")
        self._session_log = (
            Path(session_log) if session_log
            else self._job_dir / "session.log"
        )

        self._proc: Optional[subprocess.Popen] = None
        self._restart_count = 0

    # ------------------------------------------------------------------
    # Lifecycle
    # ------------------------------------------------------------------

    def start(self) -> None:
        """Start Virtuoso with the SKILL server loop."""
        self._job_dir.mkdir(parents=True, exist_ok=True)

        # Remove stale Cadence lock files that would block Virtuoso startup
        _remove_virtuoso_lock_files(self._session_log, self._label)

        # Write the server SKILL script with the actual job-dir path embedded
        server_il = self._job_dir / "server.il"
        server_il.write_text(
            _SERVER_SKILL_TEMPLATE.replace("{JOB_DIR}", str(self._job_dir))
        )

        env = os.environ.copy()
        env["DISPLAY"] = self.display

        cmd = [
            "virtuoso",
            "-log",    str(self._session_log),
            "-replay", str(server_il),
        ]

        self._proc = subprocess.Popen(
            cmd,
            cwd=str(self.virtuoso_dir),
            stdin=subprocess.DEVNULL,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
            env=env,
        )

        print(
            f"[{self._label}] Started pid={self._proc.pid}, "
            f"DISPLAY={self.display}"
        )
        print(
            f"[{self._label}] Waiting {self.STARTUP_WAIT_SEC}s for "
            f"Virtuoso to initialise..."
        )
        time.sleep(self.STARTUP_WAIT_SEC)

        if not self._is_alive():
            raise RuntimeError(
                f"Virtuoso failed to start — check {self._session_log}"
            )
        print(f"[{self._label}] Virtuoso ready.")

    def close(self) -> None:
        """Gracefully shut down the Virtuoso server loop."""
        if not self._is_alive():
            return
        # Signal the server loop to exit
        shutdown = self._job_dir / "shutdown"
        shutdown.touch()
        try:
            self._proc.wait(timeout=15)
        except subprocess.TimeoutExpired:
            self._proc.kill()
        print(f"[{self._label}] Virtuoso session closed.")

    def __enter__(self) -> "PersistentVirtuosoRunner":
        self.start()
        return self

    def __exit__(self, *args) -> None:
        self.close()

    # ------------------------------------------------------------------
    # Script execution
    # ------------------------------------------------------------------

    def run_script(
        self,
        skill_file: Path,
        log_file: Path,
        timeout: Optional[int] = None,
    ) -> VirtuosoResult:
        """
        Submit a SKILL script to the running Virtuoso instance and block
        until it completes (or times out / crashes).

        ``exit()`` calls are stripped from the script so Virtuoso stays
        alive between runs.

        Args:
            skill_file: Absolute path to the ``.il`` script to execute.
            log_file:   Destination for a per-script log excerpt.
            timeout:    Max wall-clock seconds (default: ``default_timeout``).

        Returns:
            ``VirtuosoResult`` with success flag, log text, and timing.
        """
        skill_file = Path(skill_file)
        log_file   = Path(log_file)
        timeout    = timeout or self.default_timeout

        if not skill_file.exists():
            return VirtuosoResult(
                success=False, returncode=-1, log_path=log_file,
                error_message=f"SKILL script not found: {skill_file}",
            )

        # Ensure Virtuoso is alive; restart if it crashed between jobs
        if not self._is_alive():
            err = self._safe_restart()
            if err:
                return VirtuosoResult(
                    success=False, returncode=-1, log_path=log_file,
                    error_message=err,
                )

        # Write a stripped copy of the script (remove exit() to keep Virtuoso alive)
        clean_il   = _strip_exit_calls(skill_file.read_text())
        fd, clean_path = tempfile.mkstemp(suffix=".il", prefix="virt_clean_", dir="/tmp")
        clean_file = Path(clean_path)
        os.close(fd)
        clean_file.write_text(clean_il)

        # Record session-log offset so we can extract per-script log later
        pre_offset = (
            self._session_log.stat().st_size
            if self._session_log.exists() else 0
        )

        # Submit job atomically (write to temp then rename).
        # The job file IS a SKILL expression that loads the clean script.
        # The server loads it directly — no SKILL file-reading needed.
        job_file    = self._job_dir / "pending.job"
        result_file = self._job_dir / "result.done"
        result_file.unlink(missing_ok=True)   # clear stale result

        tmp_job = self._job_dir / "pending.job.tmp"
        tmp_job.write_text(f'load("{clean_file}")\n')
        tmp_job.rename(job_file)              # atomic on POSIX

        t0 = time.time()
        timed_out    = False
        process_died = False

        # Poll until result appears, Virtuoso dies, or timeout
        while time.time() - t0 < timeout:
            if result_file.exists():
                break
            if not self._is_alive():
                process_died = True
                break
            time.sleep(self.POLL_INTERVAL)
        else:
            timed_out = True

        elapsed  = time.time() - t0

        # Cleanup temporary cleaned script
        try:
            clean_file.unlink(missing_ok=True)
        except Exception:
            pass

        # Extract per-script log snippet from the session log
        log_text = _read_log_from(self._session_log, pre_offset)

        # --- Handle timeout ---
        if timed_out:
            job_file.unlink(missing_ok=True)
            if self._is_alive():
                self._proc.kill()
                self._proc.wait(timeout=5)
            msg = f"Virtuoso timed out after {timeout}s"
            self._safe_restart()
            return VirtuosoResult(
                success=False, returncode=-1, log_path=log_file,
                log_text=log_text, elapsed_sec=elapsed, error_message=msg,
            )

        # --- Handle unexpected process death (no result written) ---
        if process_died and not result_file.exists():
            msg = "Virtuoso process died before completing the script"
            self._safe_restart()
            return VirtuosoResult(
                success=False, returncode=-1, log_path=log_file,
                log_text=log_text, elapsed_sec=elapsed, error_message=msg,
            )

        # Process died but DID write result (shouldn't happen since we strip
        # exit(), but handle it gracefully by restarting for next run)
        if process_died and result_file.exists():
            self._safe_restart()

        # Read and consume the result marker
        result_text = ""
        if result_file.exists():
            result_text = result_file.read_text().strip()
            result_file.unlink(missing_ok=True)

        # Write per-script log file for diagnostics
        log_file.parent.mkdir(parents=True, exist_ok=True)
        log_file.write_text(log_text)

        skill_error = _check_skill_errors(log_text)

        if result_text.startswith("ERROR"):
            return VirtuosoResult(
                success=False, returncode=1, log_path=log_file,
                log_text=log_text, elapsed_sec=elapsed,
                error_message=result_text,
            )

        success = (result_text == "DONE") and not skill_error
        return VirtuosoResult(
            success=success,
            returncode=0 if success else 1,
            log_path=log_file,
            log_text=log_text,
            elapsed_sec=elapsed,
            error_message=(
                skill_error or
                ("" if success else f"Unexpected result marker: {result_text!r}")
            ),
        )

    # ------------------------------------------------------------------
    # Internal helpers
    # ------------------------------------------------------------------

    def _is_alive(self) -> bool:
        return self._proc is not None and self._proc.poll() is None

    def _restart(self) -> None:
        if self._restart_count >= self.max_restarts:
            raise RuntimeError(
                f"Virtuoso crashed {self.max_restarts} times in a row — aborting."
            )
        self._restart_count += 1
        print(
            f"[{self._label}] Restarting Virtuoso "
            f"(attempt {self._restart_count}/{self.max_restarts})..."
        )
        if self._proc and self._proc.poll() is None:
            self._proc.kill()
            self._proc.wait(timeout=5)
        self.start()

    def _safe_restart(self) -> Optional[str]:
        """Restart without raising; returns None on success or an error string."""
        try:
            self._restart()
            return None
        except RuntimeError as e:
            return str(e)


# ---------------------------------------------------------------------------
# Module-level helpers
# ---------------------------------------------------------------------------

def _strip_exit_calls(text: str) -> str:
    """
    Remove ``exit()`` / ``exit(0)`` / ``exit(1)`` lines from a SKILL script
    so that Virtuoso does not terminate after executing the script.
    """
    return re.sub(
        r"^\s*exit\s*\(\s*\d*\s*\)\s*;?\s*$",
        "",
        text,
        flags=re.MULTILINE,
    )


def _read_log(log_file: Path) -> str:
    """Read a log file; return empty string if it doesn't exist yet."""
    try:
        return log_file.read_text(errors="replace")
    except FileNotFoundError:
        return ""


def _read_log_from(log_file: Path, offset: int) -> str:
    """Read only the bytes appended to ``log_file`` since ``offset``."""
    try:
        with log_file.open("rb") as f:
            f.seek(offset)
            return f.read().decode(errors="replace")
    except FileNotFoundError:
        return ""


_SKILL_ERROR_PATTERNS = ("*Error", "**Error", "FATAL", "Cannot find procedure")


def _check_skill_errors(log_text: str) -> Optional[str]:
    """
    Scan log text for known SKILL/Virtuoso error signatures.
    Returns the first offending line, or None if clean.
    """
    for line in log_text.splitlines():
        for pattern in _SKILL_ERROR_PATTERNS:
            if pattern.lower() in line.lower():
                return line.strip()
    return None
